create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[A-Za-z0-9_]{2,18}$'),
  display_name text not null check (char_length(display_name) between 1 and 18),
  avatar_seed integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.diaries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  diary_date date not null,
  mood text not null default '평온',
  title text not null default '',
  content text not null default '',
  youtube text not null default '',
  updated_at timestamptz not null default now(),
  unique (user_id, diary_date)
);

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  addressee_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'accepted' check (status in ('accepted')),
  created_at timestamptz not null default now(),
  check (requester_id <> addressee_id),
  unique (requester_id, addressee_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  receiver_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now(),
  check (sender_id <> receiver_id)
);

create index if not exists diaries_user_date_idx on public.diaries(user_id, diary_date);
create index if not exists friendships_requester_idx on public.friendships(requester_id);
create index if not exists friendships_addressee_idx on public.friendships(addressee_id);
create index if not exists messages_sender_idx on public.messages(sender_id);
create index if not exists messages_receiver_idx on public.messages(receiver_id);

alter table public.profiles enable row level security;
alter table public.diaries enable row level security;
alter table public.friendships enable row level security;
alter table public.messages enable row level security;

revoke all on table public.profiles, public.diaries, public.friendships, public.messages from anon;
grant select on table public.profiles to anon;
grant select, insert, update on table public.profiles to authenticated;
grant select, insert, update, delete on table public.diaries to authenticated;
grant select, insert, delete on table public.friendships to authenticated;
grant select, insert on table public.messages to authenticated;

drop policy if exists "profiles read signed in" on public.profiles;
create policy "profiles read signed in" on public.profiles for select to anon, authenticated using (true);

drop policy if exists "profile create self" on public.profiles;
create policy "profile create self" on public.profiles for insert to authenticated with check ((select auth.uid()) = id);

drop policy if exists "profile update self" on public.profiles;
create policy "profile update self" on public.profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

drop policy if exists "diary read self" on public.diaries;
create policy "diary read self" on public.diaries for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "diary insert self" on public.diaries;
create policy "diary insert self" on public.diaries for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "diary update self" on public.diaries;
create policy "diary update self" on public.diaries for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "diary delete self" on public.diaries;
create policy "diary delete self" on public.diaries for delete to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "friendships read participant" on public.friendships;
create policy "friendships read participant" on public.friendships for select to authenticated using ((select auth.uid()) in (requester_id, addressee_id));
drop policy if exists "friendships create self" on public.friendships;
create policy "friendships create self" on public.friendships for insert to authenticated with check ((select auth.uid()) = requester_id);
drop policy if exists "friendships delete participant" on public.friendships;
create policy "friendships delete participant" on public.friendships for delete to authenticated using ((select auth.uid()) in (requester_id, addressee_id));

drop policy if exists "messages read participant" on public.messages;
create policy "messages read participant" on public.messages for select to authenticated using ((select auth.uid()) in (sender_id, receiver_id));
drop policy if exists "messages send self" on public.messages;
create policy "messages send self" on public.messages for insert to authenticated with check ((select auth.uid()) = sender_id);
